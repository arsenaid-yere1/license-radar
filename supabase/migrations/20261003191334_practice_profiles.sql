create function private.audit_practice() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    insert into private.practice_audit_events
        (practice_id, actor_user_id, operation, before_name,
         before_timezone, after_name, after_timezone)
    values (new.id, auth.uid(),
            case when tg_op = 'INSERT' then 'created' else 'updated' end,
            case when tg_op = 'UPDATE' then old.name end,
            case when tg_op = 'UPDATE' then old.timezone end,
            new.name, new.timezone);
    return new;
end;
$$;
revoke all on function private.audit_practice() from public, anon, authenticated;
create trigger audit_practice after insert or update on public.practices
for each row execute function private.audit_practice();
