create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.practices (
    id uuid primary key default gen_random_uuid(),
    owner_user_id uuid not null default auth.uid()
    references auth.users (id) on delete restrict,
    name text not null check (char_length(name) between 1 and 120),
    timezone text not null,
    version integer not null default 1 check (version > 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint practices_owner_user_id_key unique (owner_user_id)
);
alter table public.practices enable row level security;
revoke all on public.practices from public, anon, authenticated;
grant select on public.practices to authenticated;
grant insert (name, timezone), update (name, timezone) on public.practices to authenticated;
create policy practices_select on public.practices for select to authenticated
using (owner_user_id = (select auth.uid()));
create policy practices_insert on public.practices for insert to authenticated
with check (owner_user_id = (select auth.uid()));
create policy practices_update on public.practices for update to authenticated
using (owner_user_id = (select auth.uid())) with check (owner_user_id = (select auth.uid()));

create table private.practice_audit_events (
    id uuid primary key default gen_random_uuid(),
    practice_id uuid not null references public.practices (id) on delete restrict,
    actor_user_id uuid not null references auth.users (id) on delete restrict,
    operation text not null check (operation in ('created', 'updated')),
    before_name text,
    before_timezone text,
    after_name text not null,
    after_timezone text not null,
    occurred_at timestamptz not null default clock_timestamp()
);
create index practice_audit_events_practice_id_idx
on private.practice_audit_events (practice_id);
create index practice_audit_events_actor_user_id_idx
on private.practice_audit_events (actor_user_id);
alter table private.practice_audit_events enable row level security;
revoke all on private.practice_audit_events from public, anon, authenticated;

